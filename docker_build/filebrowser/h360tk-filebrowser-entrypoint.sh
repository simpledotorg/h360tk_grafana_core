#!/bin/sh
# ---------------------------------------------------------------------------
# Generates FileBrowser's config.yaml at container start, then runs FileBrowser.
#
# FileBrowser reads its sub-path ONLY from a config file - there is no
# environment variable for it, which is what used to force each H360 instance
# onto its own subdomain. Generating the file here means a country repo sets
# H360TK_BASE_PATH in .env and nothing else: the base URL can no longer drift
# out of sync with the instance's prefix.
#
# Environment:
#   H360TK_BASE_PATH           instance prefix, e.g. /demo ("" = domain root)
#   H360TK_UPLOAD_SEGMENT      path segment under the prefix (default upload)
#   H360TK_FILEBROWSER_SOURCE  in-container directory to serve (default /srv);
#                              must match the .upload bind mount
#   FILEBROWSER_CONFIG         where to write the config (set by the image)
#
# The file is rewritten on every start. FileBrowser keeps users, shares and
# sessions in its database, not here, so only declarative settings are reset.
# ---------------------------------------------------------------------------
set -eu

BASE_PATH="${H360TK_BASE_PATH:-}"
SEGMENT="${H360TK_UPLOAD_SEGMENT:-upload}"
SOURCE="${H360TK_FILEBROWSER_SOURCE:-/srv}"
CONFIG="${FILEBROWSER_CONFIG:-/home/filebrowser/data/config.yaml}"
BINARY="${H360TK_FILEBROWSER_BINARY:-/home/filebrowser/filebrowser}"

# Normalise to either "" (root) or "/segment" with no trailing slash.
case "$BASE_PATH" in
    "" | "/") BASE_PATH="" ;;
    /*)       BASE_PATH="${BASE_PATH%/}" ;;
    *)        BASE_PATH="/${BASE_PATH%/}" ;;
esac

SEGMENT="${SEGMENT#/}"
SEGMENT="${SEGMENT%/}"

if [ -n "$SEGMENT" ]; then
    BASE_URL="${BASE_PATH}/${SEGMENT}/"
else
    BASE_URL="${BASE_PATH}/"
fi

CONFIG_DIR="$(dirname "$CONFIG")"
if ! mkdir -p "$CONFIG_DIR" 2>/dev/null || [ ! -w "$CONFIG_DIR" ]; then
    echo "h360tk-filebrowser: cannot write $CONFIG_DIR." >&2
    echo "h360tk-filebrowser: if you bind-mount it, it must be writable by uid 1000." >&2
    exit 1
fi

cat > "$CONFIG" <<EOF
# Generated by h360tk-filebrowser-entrypoint.sh at container start.
# Do not edit in place - it is rewritten on every restart. Change
# H360TK_BASE_PATH in the instance's .env instead.
server:
  sources:
    - path: "${SOURCE}"
      config:
        defaultEnabled: true

http:
  baseURL: "${BASE_URL}"
  # Trust X-Forwarded-* from the instance proxy, which is the only route in
  # once the direct host port is closed.
  trustProxyHeaders: true
EOF

echo "h360tk-filebrowser: serving ${SOURCE} at ${BASE_URL} (config ${CONFIG})"

exec "$BINARY" "$@"
