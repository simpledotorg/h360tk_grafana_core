#!/bin/sh
# ---------------------------------------------------------------------------
# Renders /etc/nginx/conf.d/default.conf for one H360 instance.
#
# Run by the stock nginx entrypoint (/docker-entrypoint.d/*.sh) before nginx
# starts, so the config is built from the environment of the running container
# and nothing has to be bind-mounted into a country repo.
#
# Environment:
#   H360TK_BASE_PATH          URL prefix this instance is served under, e.g.
#                             /demo. Empty or "/" serves it at the domain root.
#   H360TK_UPSTREAM_DASHBOARD host:port for Grafana (default grafana:3000).
#   H360TK_ROUTES             space-separated <segment>=<host>:<port> list of
#                             sub-routes, e.g. "upload=filebrowser:80
#                             sftp=sftpgo:8080". Empty means no sub-routes.
#   H360TK_MAX_BODY_SIZE      client_max_body_size (default 2g).
#   H360TK_RESOLVER           DNS for runtime upstream resolution
#                             (default 127.0.0.11, Docker's embedded DNS).
#
# Upstreams are resolved at REQUEST time, not at startup: every proxy_pass
# goes through a variable. nginx resolves a literal upstream name when it
# parses the config, so a service that is slow to start - or a route for a
# service this instance does not run - would otherwise stop nginx from
# booting at all. With a variable, that route simply returns 502 and the rest
# of the instance keeps serving.
#
# The prefix is never stripped. Grafana (serve_from_sub_path) and FileBrowser
# (http.baseURL) both emit absolute URLs that already contain it and expect to
# receive it back, so $request_uri is passed through verbatim.
# ---------------------------------------------------------------------------
set -eu

BASE_PATH="${H360TK_BASE_PATH:-}"
DASHBOARD="${H360TK_UPSTREAM_DASHBOARD:-grafana:3000}"
ROUTES="${H360TK_ROUTES:-}"
MAX_BODY="${H360TK_MAX_BODY_SIZE:-2g}"
RESOLVER="${H360TK_RESOLVER:-127.0.0.11}"
# Overridable so the renderer can be exercised outside the image.
CONF="${H360TK_CONF_PATH:-/etc/nginx/conf.d/default.conf}"

# Normalise to either "" (root) or "/segment" with no trailing slash.
case "$BASE_PATH" in
    "" | "/") BASE_PATH="" ;;
    /*)       BASE_PATH="${BASE_PATH%/}" ;;
    *)        BASE_PATH="/${BASE_PATH%/}" ;;
esac

echo "h360tk-proxy: base path '${BASE_PATH:-/}', dashboard ${DASHBOARD}, routes '${ROUTES}'"

# Shared proxy directives. $1 is the upstream host:port.
emit_proxy_body() {
    cat <<EOF
        set \$h360tk_upstream "http://$1";
        proxy_pass \$h360tk_upstream\$request_uri;
        proxy_http_version 1.1;

        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$h360tk_forwarded_proto;
        proxy_set_header X-Forwarded-Host  \$host;
        proxy_set_header Upgrade           \$http_upgrade;
        proxy_set_header Connection        \$h360tk_connection_upgrade;

        # Uploads and server-sent events must not be buffered.
        proxy_buffering         off;
        proxy_request_buffering off;
        proxy_read_timeout      3600s;
        proxy_send_timeout      3600s;
EOF
}

{
    cat <<EOF
# Generated by h360tk-render-conf.sh at container start. Do not edit in place:
# it is rewritten on every restart. Change the H360TK_* environment variables
# in the instance's .env instead.

# Honour the scheme the shared edge terminated TLS with; fall back to ours when
# the instance is reached directly (local dev, debugging on the box).
map \$http_x_forwarded_proto \$h360tk_forwarded_proto {
    default \$http_x_forwarded_proto;
    ''      \$scheme;
}

map \$http_upgrade \$h360tk_connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 80 default_server;
    server_name _;

    # Emit relative Location headers. nginx would otherwise build absolute
    # URLs from the Host header and its own listening port - which is plain
    # HTTP on 80 inside the container - so every redirect behind the
    # TLS-terminating edge would point at http:// and lose the port in local
    # testing. Relative redirects are resolved by the browser against the
    # scheme, host and port it actually used.
    absolute_redirect off;

    resolver ${RESOLVER} valid=10s ipv6=off;

    # Line lists are uploaded through here; nginx's 1m default would reject
    # them with a 413 before the upload UI ever saw the request.
    client_max_body_size ${MAX_BODY};

    # Health check for the shared edge / load balancer. Deliberately outside
    # the instance prefix so a misconfigured prefix still reports honestly.
    location = /healthz {
        access_log off;
        default_type text/plain;
        return 200 "ok\n";
    }
EOF

    # --- sub-routes -------------------------------------------------------
    # nginx picks the longest matching prefix, so these win over the dashboard
    # location regardless of the order they are emitted in.
    for route in $ROUTES; do
        segment="${route%%=*}"
        upstream="${route#*=}"
        if [ "$segment" = "$route" ] || [ -z "$upstream" ] || [ -z "$segment" ]; then
            echo "h360tk-proxy: ignoring malformed route '$route' (want segment=host:port)" >&2
            continue
        fi
        echo "h360tk-proxy:   ${BASE_PATH}/${segment}/ -> ${upstream}" >&2
        cat <<EOF

    location = ${BASE_PATH}/${segment} {
        return 301 ${BASE_PATH}/${segment}/\$is_args\$args;
    }

    location ${BASE_PATH}/${segment}/ {
EOF
        emit_proxy_body "$upstream"
        echo "    }"
    done

    # --- dashboard --------------------------------------------------------
    if [ -n "$BASE_PATH" ]; then
        cat <<EOF

    # Hitting the box directly with no path lands on this instance.
    location = / {
        return 302 ${BASE_PATH}/;
    }

    location = ${BASE_PATH} {
        return 301 ${BASE_PATH}/\$is_args\$args;
    }

    location ${BASE_PATH}/ {
EOF
        emit_proxy_body "$DASHBOARD"
        cat <<'EOF'
    }

    # Anything outside this instance's prefix is not ours to serve.
    location / {
        default_type text/plain;
        return 404 "No H360 instance is served from this path on this host.\n";
    }
}
EOF
    else
        # Served at the domain root: the dashboard IS the catch-all.
        cat <<EOF

    location / {
EOF
        emit_proxy_body "$DASHBOARD"
        cat <<'EOF'
    }
}
EOF
    fi
} > "$CONF"

echo "h360tk-proxy: wrote $CONF"
